-- Импортированный high-water прогресс. Закладки Remanga могут содержать
-- больше прочитанных глав, чем сейчас доступно у источника: закрытые,
-- удалённые или ещё не появившиеся главы. Отметка монотонная — хранит
-- максимум импортированного `progress` и не уменьшается при ручном снятии
-- отметок. Эффективный прогресс считается как
-- `MAX(chapter_reads, imported_read_count)`.
--
-- Бэкфилл невозможен: числа из старого импорта в БД нет. У старых тайтлов
-- high-water появится только после повторного импорта закладок.

ALTER TABLE library ADD COLUMN imported_read_count INTEGER;
